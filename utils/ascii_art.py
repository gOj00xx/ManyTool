def get_ascii(name='main'):
    """Get ASCII art by name"""
    arts = {
        'main': MAIN_ASCII,
        'ddos': DDOS_ASCII,
        'spam_wa': SPAM_WA_ASCII,
        'roblox': ROBLOX_ASCII,
        'tiktok': TIKTOK_ASCII,
        'wifi': WIFI_ASCII,
        'info': INFO_ASCII
    }
    return arts.get(name, MAIN_ASCII)
